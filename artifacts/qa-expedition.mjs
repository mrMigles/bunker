const report = { prep: true, departure: true, errors: [] };
await page.evaluate(()=>window.__net.send({k:'debug',op:'speed',arg:20}));
const destination=await page.evaluate(()=>Object.values(window.__net.pub.mods.wmap.nodes).find(n=>n.type==='shop'));
console.log('DEST',destination);
await page.locator(`.wmap g[aria-label="${destination.name}"]`).click();
await page.getByRole('button',{name:'Проложить маршрут →',exact:true}).click();
