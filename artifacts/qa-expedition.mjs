await page.waitForTimeout(800);
await page.screenshot({path:'artifacts/expedition-site.png'});
report.entry=true;
let target=await page.evaluate(()=>{const e=window.__net.pub.mods.expedition;const c=window.__net.myChar();return e.site.conts.filter(o=>o.lv===c.lv&&!o.locked&&o.searched<1&&e.site.rooms.some(r=>r.revealed&&r.lv===o.lv&&o.x>=r.x&&o.x<r.x+r.w)).sort((a,b)=>Math.abs(a.x-c.x)-Math.abs(b.x-c.x))[0]});
if (!target) {
  await page.locator('.exp-world-marker[aria-label="Дверь"]').first().click();
  const doorAction=page.locator('.exp-context button.exp-action').filter({hasText:/Открыть дверь|Выбить/}).first();
  await doorAction.click({timeout:20000});
  await page.waitForTimeout(1800);
  const dest=await page.evaluate(()=>{const s=window.__net.pub.mods.expedition.site,c=window.__net.myChar();const d=s.doors.filter(d=>d.lv===c.lv).sort((a,b)=>a.x-b.x)[0];return {x:d.x+1.5,lv:d.lv};});
  const point=await page.evaluate(p=>window.__game.exp.site.toScreen(p.x,-(p.lv*2+2)+.7),dest);
  await page.mouse.click(point[0],point[1]);
  await page.waitForTimeout(3500);
  target=await page.evaluate(()=>{const e=window.__net.pub.mods.expedition;const c=window.__net.myChar();return e.site.conts.filter(o=>o.lv===c.lv&&!o.locked&&o.searched<1&&e.site.rooms.some(r=>r.revealed&&r.lv===o.lv&&o.x>=r.x&&o.x<r.x+r.w)).sort((a,b)=>Math.abs(a.x-c.x)-Math.abs(b.x-c.x))[0]});
}
console.log('TARGET',target);
